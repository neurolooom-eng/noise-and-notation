-- =====================================================================
-- 0003 — Dynamic, versioned questions
--
--  * Questions get a stable id; any number can be added; position is just
--    the display order. The old 1..6 limit is removed.
--  * ANY change to a question (dimension, statement, scale, active, position)
--    increments that question's version automatically, and bumps the global
--    question_set_version.
--  * question_versions keeps the exact wording of every version, so reports
--    can show what each version said.
--  * Answers move from fixed columns q1..q6 on responses to one row per
--    answer in response_answers, each tagged with the question version it
--    was answered under. Existing q1..q6 data is migrated.
--  * submit_feedback now takes [{question_id, version, rating}, …] and
--    rejects a submission made against out-of-date questions.
--
-- Safe to re-run.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. questions: stable id, free ordering
-- ---------------------------------------------------------------------
alter table public.questions add column if not exists id bigint generated by default as identity;

do $$
begin
  -- move the primary key from position to id
  if exists (select 1 from pg_constraint where conname = 'questions_pkey'
             and conrelid = 'public.questions'::regclass
             and pg_get_constraintdef(oid) like '%(\"position\")%' escape '\') then
    alter table public.questions drop constraint questions_pkey;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'questions_pkey'
                 and conrelid = 'public.questions'::regclass) then
    alter table public.questions add constraint questions_pkey primary key (id);
  end if;
  if exists (select 1 from pg_constraint where conname = 'questions_position_check'
             and conrelid = 'public.questions'::regclass) then
    alter table public.questions drop constraint questions_position_check;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'questions_scale_check') then
    alter table public.questions add constraint questions_scale_check
      check (scale_min >= 0 and scale_max <= 10 and scale_min < scale_max);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'questions_text_check') then
    alter table public.questions add constraint questions_text_check
      check (char_length(btrim(statement)) > 0 and char_length(btrim(dimension)) > 0);
  end if;
end $$;

alter table public.questions alter column position type int;
alter table public.questions alter column version set default 1;
create index if not exists questions_position_idx on public.questions(position, id);

-- ---------------------------------------------------------------------
-- 2. Version history
-- ---------------------------------------------------------------------
create table if not exists public.question_versions (
  question_id bigint not null references public.questions(id) on delete cascade,
  version int not null,
  position int not null,
  dimension text not null,
  statement text not null,
  scale_min smallint not null,
  scale_max smallint not null,
  active boolean not null,
  changed_at timestamptz not null default now(),
  changed_by text,
  primary key (question_id, version)
);

-- Seed history for existing questions (current state = their current version).
insert into public.question_versions (question_id, version, position, dimension, statement, scale_min, scale_max, active, changed_at)
select id, version, position, dimension, statement, scale_min, scale_max, active, updated_at
from public.questions
on conflict do nothing;

-- ---------------------------------------------------------------------
-- 3. Versioning triggers: ANY change => version + 1
-- ---------------------------------------------------------------------
drop trigger if exists trg_bump_question_version on public.questions;
drop function if exists public.bump_question_version();

create or replace function public.question_before_write()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.version := 1;
    if new.position is null then
      select coalesce(max(position), 0) + 1 into new.position from questions;
    end if;
  elsif (new.dimension, new.statement, new.scale_min, new.scale_max, new.active, new.position)
        is distinct from
        (old.dimension, old.statement, old.scale_min, old.scale_max, old.active, old.position) then
    new.version := old.version + 1;
  else
    return new;  -- nothing meaningful changed: keep version
  end if;
  new.dimension := btrim(new.dimension);
  new.statement := btrim(new.statement);
  new.updated_at := now();
  update settings set value = (value::int + 1)::text, updated_at = now()
   where key = 'question_set_version';
  return new;
end;
$$;

create or replace function public.question_after_write()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into question_versions (question_id, version, position, dimension, statement,
                                 scale_min, scale_max, active, changed_at, changed_by)
  values (new.id, new.version, new.position, new.dimension, new.statement,
          new.scale_min, new.scale_max, new.active, now(), auth.jwt() ->> 'email')
  on conflict (question_id, version) do nothing;
  return new;
end;
$$;

drop trigger if exists trg_question_before_write on public.questions;
create trigger trg_question_before_write
  before insert or update on public.questions
  for each row execute function public.question_before_write();

drop trigger if exists trg_question_after_write on public.questions;
create trigger trg_question_after_write
  after insert or update on public.questions
  for each row execute function public.question_after_write();

-- Questions are never deleted once answered (deactivate instead).
create or replace function public.question_block_delete()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if exists (select 1 from response_answers where question_id = old.id) then
    raise exception 'This question has answers. Set it inactive instead of deleting it.' using errcode = 'P0001';
  end if;
  return old;
end;
$$;

-- ---------------------------------------------------------------------
-- 4. One row per answer
-- ---------------------------------------------------------------------
create table if not exists public.response_answers (
  response_id bigint not null references public.responses(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete restrict,
  question_version int not null,
  rating smallint not null check (rating between 0 and 10),
  primary key (response_id, question_id),
  foreign key (question_id, question_version) references public.question_versions(question_id, version)
);
create index if not exists response_answers_q_idx on public.response_answers(question_id, question_version);

drop trigger if exists trg_question_block_delete on public.questions;
create trigger trg_question_block_delete
  before delete on public.questions
  for each row execute function public.question_block_delete();

-- Views from 0001 depend on q1..q6; drop them before migrating columns.
drop view if exists public.session_summary;
drop view if exists public.cohort_summary;

-- Migrate legacy q1..q6 answers (position N => question at position N, its current version).
do $$
declare n int;
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'responses' and column_name = 'q1') then
    for n in 1..6 loop
      execute format($f$
        insert into public.response_answers (response_id, question_id, question_version, rating)
        select r.id, q.id, q.version, r.q%1$s
        from public.responses r
        join public.questions q on q.position = %1$s
        where r.q%1$s is not null
        on conflict do nothing$f$, n);
    end loop;
    alter table public.responses drop column q1, drop column q2, drop column q3,
                                 drop column q4, drop column q5, drop column q6;
  end if;
end $$;

