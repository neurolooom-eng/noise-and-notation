create or replace function public.get_app_config()
returns jsonb
language sql stable security definer set search_path = public
as $$
  select jsonb_build_object(
    'settings', (select jsonb_object_agg(key, value) from settings
                  where key in ('app_title','privacy_why','privacy_how','consent_text',
                                'contact_hint','comment_prompt','question_set_version')),
    'cohorts', coalesce((select jsonb_agg(jsonb_build_object(
                  'id', id, 'course_name', course_name, 'cohort', cohort)
                  order by course_name, cohort)
                from cohorts where active), '[]'::jsonb),
    'questions', coalesce((select jsonb_agg(jsonb_build_object(
                  'id', id, 'position', position, 'version', version,
                  'dimension', dimension, 'statement', statement,
                  'scale_min', scale_min, 'scale_max', scale_max) order by position, id)
                from questions where active), '[]'::jsonb)
  );
$$;

drop function if exists public.submit_feedback(text, bigint, smallint[], text);

-- p_answers: [{"question_id": 1, "version": 3, "rating": 4}, …]
create or replace function public.submit_feedback(
  p_contact text, p_session_id bigint, p_answers jsonb, p_comment text)
returns jsonb
language plpgsql volatile security definer set search_path = public
as $$
declare
  n record; v_code text; s record; v_set int; v_resp bigint;
  q record; a jsonb; v_rating int; v_count int;
begin
  select * into n from normalize_contact(p_contact);
  select code into v_code from participants where contact = n.contact;
  if v_code is null then
    raise exception 'We could not find your registration. Please register first.' using errcode = 'P0001';
  end if;

  select s2.* into s from sessions s2 join cohorts c on c.id = s2.cohort_id
   where s2.id = p_session_id and s2.feedback_open and c.active;
  if not found then
    raise exception 'Feedback for this session is closed.' using errcode = 'P0001';
  end if;

  if exists (select 1 from responses where session_id = p_session_id and participant_code = v_code) then
    raise exception 'You have already submitted feedback for this session.' using errcode = 'P0001';
  end if;

  if p_answers is null or jsonb_typeof(p_answers) <> 'array' then
    raise exception 'Invalid answers.' using errcode = 'P0001';
  end if;

  -- The submitted set must be exactly the current active questions, at their current versions.
  select count(*) into v_count from jsonb_array_elements(p_answers);
  if v_count <> (select count(*) from questions where active) then
    raise exception 'The questions were updated while you were answering. Please tap Refresh and try again.' using errcode = 'P0001';
  end if;
  for q in select id, version, scale_min, scale_max from questions where active loop
    a := null;
    select e into a from jsonb_array_elements(p_answers) e
     where (e ->> 'question_id')::bigint = q.id limit 1;
    if a is null or (a ->> 'version')::int is distinct from q.version then
      raise exception 'The questions were updated while you were answering. Please tap Refresh and try again.' using errcode = 'P0001';
    end if;
    v_rating := (a ->> 'rating')::int;
    if v_rating is null or v_rating < q.scale_min or v_rating > q.scale_max then
      raise exception 'Please rate every statement.' using errcode = 'P0001';
    end if;
  end loop;

  select value::int into v_set from settings where key = 'question_set_version';

  insert into responses (cohort_id, session_id, participant_code, comment, question_set_version)
  values (s.cohort_id, s.id, v_code, nullif(btrim(coalesce(p_comment, '')), ''), coalesce(v_set, 1))
  returning id into v_resp;

  insert into response_answers (response_id, question_id, question_version, rating)
  select v_resp, (e ->> 'question_id')::bigint, (e ->> 'version')::int, (e ->> 'rating')::smallint
  from jsonb_array_elements(p_answers) e;

  return jsonb_build_object('ok', true);
exception
  when unique_violation then
    raise exception 'You have already submitted feedback for this session.' using errcode = 'P0001';
end;
$$;

revoke all on function public.submit_feedback(text, bigint, jsonb, text) from public;
grant execute on function public.submit_feedback(text, bigint, jsonb, text) to anon, authenticated;

revoke all on function public.question_before_write() from public, anon;
