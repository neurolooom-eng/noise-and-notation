-- 7. Summary views (admin only; averages hidden below the minimum)
-- ---------------------------------------------------------------------
-- Per session: response count and overall average.
create or replace view public.session_summary
with (security_invoker = true) as
with m as (select coalesce((select value::int from public.settings
                             where key = 'min_responses_for_summary'), 5) as min_n),
r as (select r.session_id, count(*)::int as n from public.responses r group by r.session_id),
a as (select r.session_id, round(avg(ra.rating), 2) as avg_all
      from public.responses r join public.response_answers ra on ra.response_id = r.id
      group by r.session_id)
select
  c.id as cohort_id, c.course_name, c.cohort,
  s.id as session_id, s.session_number, s.title, s.session_date, s.topic, s.feedback_open,
  coalesce(r.n, 0) as response_count,
  (coalesce(r.n, 0) >= m.min_n) as averages_visible,
  case when coalesce(r.n, 0) >= m.min_n then a.avg_all end as overall_avg
from public.sessions s
join public.cohorts c on c.id = s.cohort_id
cross join m
left join r on r.session_id = s.id
left join a on a.session_id = s.id;

-- Per session × question × version.
create or replace view public.session_question_summary
with (security_invoker = true) as
with m as (select coalesce((select value::int from public.settings
                             where key = 'min_responses_for_summary'), 5) as min_n)
select
  r.session_id, ra.question_id, ra.question_version,
  qv.position, qv.dimension, qv.statement,
  count(*)::int as answer_count,
  (count(*) >= m.min_n) as average_visible,
  case when count(*) >= m.min_n then round(avg(ra.rating), 2) end as avg_rating
from public.responses r
join public.response_answers ra on ra.response_id = r.id
join public.question_versions qv on qv.question_id = ra.question_id and qv.version = ra.question_version
cross join m
group by r.session_id, ra.question_id, ra.question_version, qv.position, qv.dimension, qv.statement, m.min_n;

-- Per cohort: totals.
create or replace view public.cohort_summary
with (security_invoker = true) as
with m as (select coalesce((select value::int from public.settings
                             where key = 'min_responses_for_summary'), 5) as min_n)
select
  c.id as cohort_id, c.course_name, c.cohort,
  count(distinct r.session_id)::int as sessions_with_feedback,
  count(distinct r.id)::int as response_count,
  (count(distinct r.id) >= m.min_n) as averages_visible,
  case when count(distinct r.id) >= m.min_n then round(avg(ra.rating), 2) end as overall_avg
from public.cohorts c
cross join m
join public.responses r on r.cohort_id = c.id
left join public.response_answers ra on ra.response_id = r.id
group by c.id, c.course_name, c.cohort, m.min_n;

-- Per cohort × question × version (compare across courses on identical wording).
create or replace view public.cohort_question_summary
with (security_invoker = true) as
with m as (select coalesce((select value::int from public.settings
                             where key = 'min_responses_for_summary'), 5) as min_n)
select
  r.cohort_id, ra.question_id, ra.question_version,
  qv.position, qv.dimension, qv.statement,
  count(*)::int as answer_count,
  (count(*) >= m.min_n) as average_visible,
  case when count(*) >= m.min_n then round(avg(ra.rating), 2) end as avg_rating
from public.responses r
join public.response_answers ra on ra.response_id = r.id
join public.question_versions qv on qv.question_id = ra.question_id and qv.version = ra.question_version
cross join m
group by r.cohort_id, ra.question_id, ra.question_version, qv.position, qv.dimension, qv.statement, m.min_n;

revoke all on public.session_summary, public.session_question_summary,
              public.cohort_summary, public.cohort_question_summary from anon;
grant select on public.session_summary, public.session_question_summary,
                public.cohort_summary, public.cohort_question_summary to authenticated;

